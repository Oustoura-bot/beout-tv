import { createClient } from '@supabase/supabase-js';
import * as dotenv from 'dotenv';
import * as path from 'path';

dotenv.config({ path: path.resolve(process.cwd(), '.env.local') });

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL!;
const supabaseServiceKey = process.env.SUPABASE_SERVICE_ROLE_KEY!;
const supabase = createClient(supabaseUrl, supabaseServiceKey);

async function expandTunisiaArticle() {
  const tunisiaContent = `تستعد الكرة التونسية لمرحلة انتقالية هامة في مسيرتها نحو مونديال 2026، حيث يطمح "نسور قرطاج" إلى تقديم أداء مشرف يعكس عراقة وتاريخ المنتخب التونسي في المحافل الدولية. بعد المشاركات السابقة التي أظهرت فيها تونس ندية كبيرة أمام كبار المنتخبات، يضع الاتحاد التونسي لكرة القدم خطة عمل طموحة تهدف إلى بناء منتخب قوي يمزج بين الخبرة والشباب.

تعتمد الاستراتيجية التونسية على تعزيز صفوف المنتخب بالمواهب الناشطة في الدوريات الأوروبية، بالإضافة إلى الركائز الأساسية في الدوري المحلي. ويركز الجهاز الفني حالياً على تطوير الجوانب البدنية والتكتيكية للاعبين، مع تكثيف المباريات الودية ضد منتخبات ذات طراز عالمي لاكتساب المزيد من الخبرة والانسجام.

من الناحية التكتيكية، يسعى المنتخب التونسي إلى اعتماد أسلوب لعب متوازن يجمع بين الصلابة الدفاعية التي اشتهر بها، والفعالية الهجومية من خلال استغلال سرعة الأجنحة والمهارات الفردية لصناع اللعب. كما تلعب الجماهير التونسية دوراً محورياً في دعم المنتخب، حيث تعتبر من أكثر الجماهير حماساً ووفاءً، مما يشكل دافعاً كبيراً للاعبين لبذل أقصى جهودهم.

التحديات المقبلة تتطلب تركيزاً عالياً وعملاً دؤوباً، خاصة في ظل المنافسة الشرسة في التصفيات الإفريقية. ومع ذلك، فإن الروح القتالية والعزيمة التي يمتلكها اللاعبون التونسيون تجعل من حلم الوصول إلى أدوار متقدمة في كأس العالم 2026 هدفاً قابلاً للتحقيق، لترسيخ مكانة تونس كقوة كروية لا يستهان بها في القارة السمراء والعالم.`;

  console.log('--- تحديث مقال تونس ---');
  
  const { data, error } = await supabase
    .from('articles')
    .update({ content: tunisiaContent })
    .ilike('title', '%تونس%');

  if (error) {
    console.error('خطأ في التحديث:', error.message);
  } else {
    console.log('✅ تم توسيع محتوى مقال تونس بنجاح.');
  }
}

expandTunisiaArticle();
